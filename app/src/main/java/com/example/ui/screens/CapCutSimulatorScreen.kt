@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CapCutSimulatorScreen(
    workflows: List<Workflow>,
    selectedWorkflow: Workflow?,
    onWorkflowSelected: (Workflow) -> Unit,
    modifier: Modifier = Modifier
) {
    val coroutineScope = rememberCoroutineScope()
    val agentTelemetry = AutomationManager.agentController?.telemetry?.collectAsState()?.value
        ?: AgentTelemetry()

    var currentRunningWorkflow by remember { mutableStateOf<Workflow?>(selectedWorkflow ?: workflows.firstOrNull()) }
    var activeStepIndex by remember { mutableStateOf(-1) }
    var isSimulating by remember { mutableStateOf(false) }

    // Visual animation states
    var playheadPosition by remember { mutableFloatStateOf(160f) }
    val animatedPlayhead by animateFloatAsState(targetValue = playheadPosition, label = "playhead")

    var highlightedButtonText by remember { mutableStateOf<String?>(null) }
    var tapRippleOffset by remember { mutableStateOf<Offset?>(null) }
    var tapRippleAlpha by remember { mutableFloatStateOf(0f) }
    val animatedRippleAlpha by animateFloatAsState(targetValue = tapRippleAlpha, label = "ripple")

    // Clip segments simulated
    val clips = remember { mutableStateListOf("Clip 1 (00:00 - 00:04)", "Clip 2 (00:04 - 00:10)", "Ending Logo") }
    var captionsGenerated by remember { mutableStateOf(false) }
    var currentResolution by remember { mutableStateOf("1080P") }
    var isExporting by remember { mutableStateOf(false) }

    val timelineScrollState = rememberScrollState()

    // Trigger simulation run
    fun runSimulation(workflow: Workflow) {
        coroutineScope.launch {
            isSimulating = true
            CapCutAutomationService.log(LogLevel.INFO, "Simulator", "Started interactive visual simulation for: ${workflow.title}")

            for ((index, step) in workflow.steps.withIndex()) {
                activeStepIndex = index
                val action = step.action

                when (action.type) {
                    ActionType.CLICK_TEXT -> {
                        highlightedButtonText = action.targetText
                        if (action.targetText.equals("Split", ignoreCase = true)) {
                            clips.add(1, "Cut Clip (00:02)")
                        } else if (action.targetText.contains("caption", ignoreCase = true) || action.targetText.equals("Generate", ignoreCase = true)) {
                            captionsGenerated = true
                        } else if (action.targetText.equals("Delete", ignoreCase = true)) {
                            clips.remove("Ending Logo")
                        } else if (action.targetText.equals("Export", ignoreCase = true)) {
                            isExporting = true
                            delay(1000)
                            isExporting = false
                        }
                        delay(step.delayAfterMs)
                        highlightedButtonText = null
                    }

                    ActionType.CLICK_COORDINATES -> {
                        tapRippleOffset = Offset(action.xRatio * 700f, action.yRatio * 1200f)
                        tapRippleAlpha = 1f
                        if (action.yRatio < 0.15f) {
                            currentResolution = "4K"
                        }
                        delay(200)
                        tapRippleAlpha = 0f
                        delay(step.delayAfterMs)
                    }

                    ActionType.SWIPE_TIMELINE -> {
                        playheadPosition += 120f
                        timelineScrollState.animateScrollTo(timelineScrollState.value + 120)
                        delay(step.delayAfterMs)
                    }

                    ActionType.PINCH_ZOOM -> {
                        playheadPosition = 200f
                        delay(step.delayAfterMs)
                    }

                    ActionType.WAIT -> {
                        delay(action.durationMs)
                    }

                    else -> {
                        delay(step.delayAfterMs)
                    }
                }
            }

            isSimulating = false
            activeStepIndex = -1
            CapCutAutomationService.log(LogLevel.SUCCESS, "Simulator", "Interactive visual simulation finished")
        }
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(DarkBackground)
    ) {
        // Simulator Controls Header
        Surface(
            color = DarkSurface,
            tonalElevation = 4.dp,
            border = androidx.compose.foundation.BorderStroke(1.dp, DarkCardBorder),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(14.dp)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Surface(
                            shape = CircleShape,
                            color = NeonCyan.copy(alpha = 0.2f),
                            modifier = Modifier.size(28.dp)
                        ) {
                            Box(contentAlignment = Alignment.Center) {
                                Icon(
                                    imageVector = Icons.Default.ViewCarousel,
                                    contentDescription = null,
                                    tint = NeonCyan,
                                    modifier = Modifier.size(16.dp)
                                )
                            }
                        }
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(
                            text = "CapCut Virtual Playground",
                            style = MaterialTheme.typography.titleSmall,
                            fontWeight = FontWeight.Bold,
                            color = Color.White
                        )
                    }

                    val activeState = agentTelemetry.state
                    val badgeColor = getStateColor(activeState)
                    Surface(
                        shape = RoundedCornerShape(8.dp),
                        color = badgeColor.copy(alpha = 0.2f),
                        border = androidx.compose.foundation.BorderStroke(1.dp, badgeColor.copy(alpha = 0.6f))
                    ) {
                        Text(
                            text = if (activeState.isActive) "AGENT: ${activeState.name}" else if (isSimulating) "PLAYING MACRO" else "STANDBY",
                            style = MaterialTheme.typography.labelSmall,
                            fontFamily = FontFamily.Monospace,
                            color = badgeColor,
                            fontWeight = FontWeight.Bold,
                            modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp)
                        )
                    }
                }

                Spacer(modifier = Modifier.height(10.dp))

                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    var dropdownExpanded by remember { mutableStateOf(false) }

                    Box(modifier = Modifier.weight(1f)) {
                        OutlinedButton(
                            onClick = { dropdownExpanded = true },
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier.fillMaxWidth(),
                            contentPadding = PaddingValues(horizontal = 12.dp, vertical = 6.dp)
                        ) {
                            Text(
                                text = currentRunningWorkflow?.title ?: "Select Macro",
                                style = MaterialTheme.typography.bodySmall,
                                fontWeight = FontWeight.SemiBold,
                                maxLines = 1
                            )
                            Spacer(modifier = Modifier.width(4.dp))
                            Icon(imageVector = Icons.Default.ArrowDropDown, contentDescription = null)
                        }

                        DropdownMenu(
                            expanded = dropdownExpanded,
                            onDismissRequest = { dropdownExpanded = false },
                            modifier = Modifier.background(DarkSurface)
                        ) {
                            workflows.forEach { wf ->
                                DropdownMenuItem(
                                    text = { Text(wf.title, color = Color.White, fontSize = 13.sp) },
                                    onClick = {
                                        currentRunningWorkflow = wf
                                        onWorkflowSelected(wf)
                                        dropdownExpanded = false
                                    }
                                )
                            }
                        }
                    }

                    Button(
                        onClick = {
                            currentRunningWorkflow?.let { runSimulation(it) }
                        },
                        enabled = !isSimulating && currentRunningWorkflow != null,
                        shape = RoundedCornerShape(10.dp),
                        colors = ButtonDefaults.buttonColors(containerColor = NeonCyanDark),
                        modifier = Modifier.testTag("run_simulator_button")
                    ) {
                        Icon(imageVector = Icons.Default.PlayArrow, contentDescription = null, modifier = Modifier.size(16.dp))
                        Spacer(modifier = Modifier.width(4.dp))
                        Text("Simulate", fontWeight = FontWeight.Bold, fontSize = 12.sp)
                    }
                }
            }
        }

        // Active Step Banner in Simulator
        if (isSimulating && activeStepIndex >= 0) {
            val step = currentRunningWorkflow?.steps?.getOrNull(activeStepIndex)
            Surface(
                color = Color(0xFF072738),
                border = androidx.compose.foundation.BorderStroke(1.dp, NeonCyan),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier.padding(horizontal = 16.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(16.dp),
                        color = NeonCyan,
                        strokeWidth = 2.dp
                    )
                    Spacer(modifier = Modifier.width(10.dp))
                    Text(
                        text = "Step ${activeStepIndex + 1}: ${step?.title ?: ""}",
                        style = MaterialTheme.typography.bodySmall,
                        color = NeonCyan,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }

        // Mock CapCut Editor Viewport
        Column(
            modifier = Modifier
                .weight(1f)
                .fillMaxWidth()
                .padding(horizontal = 12.dp, vertical = 8.dp)
        ) {
            // Mock CapCut Top Header Bar
            Surface(
                shape = RoundedCornerShape(topStart = 16.dp, topEnd = 16.dp),
                color = Color(0xFF141A23),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 14.dp, vertical = 8.dp),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(imageVector = Icons.Default.Close, contentDescription = "Close", tint = Color.White, modifier = Modifier.size(18.dp))
                        Spacer(modifier = Modifier.width(12.dp))
                        Text("CapCut Project", style = MaterialTheme.typography.bodySmall, color = Color.White, fontWeight = FontWeight.Bold)
                    }

                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Surface(
                            shape = RoundedCornerShape(6.dp),
                            color = if (highlightedButtonText == "4K") NeonCyan.copy(alpha = 0.3f) else Color(0xFF232D3B),
                            border = androidx.compose.foundation.BorderStroke(1.dp, if (highlightedButtonText == "4K") NeonCyan else DarkCardBorder),
                            modifier = Modifier.clip(RoundedCornerShape(6.dp))
                        ) {
                            Text(
                                text = currentResolution,
                                style = MaterialTheme.typography.labelSmall,
                                color = if (currentResolution == "4K") NeonCyan else Color.White,
                                fontWeight = FontWeight.Bold,
                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp)
                            )
                        }

                        Spacer(modifier = Modifier.width(10.dp))

                        Surface(
                            shape = RoundedCornerShape(6.dp),
                            color = if (highlightedButtonText?.equals("Export", ignoreCase = true) == true) SunsetRose else Color(0xFF2563EB),
                            modifier = Modifier.clip(RoundedCornerShape(6.dp))
                        ) {
                            Row(
                                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                if (isExporting) {
                                    CircularProgressIndicator(modifier = Modifier.size(12.dp), color = Color.White, strokeWidth = 1.5.dp)
                                    Spacer(modifier = Modifier.width(4.dp))
                                }
                                Text("Export", style = MaterialTheme.typography.labelSmall, color = Color.White, fontWeight = FontWeight.Bold)
                            }
                        }
                    }
                }
            }

            // Video Preview Canvas
            Surface(
                color = Color(0xFF000000),
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(0.9f)
            ) {
                Box(
                    modifier = Modifier.fillMaxSize(),
                    contentAlignment = Alignment.Center
                ) {
                    // Video player mockup
                    Column(horizontalAlignment = Alignment.CenterHorizontally) {
                        Surface(
                            shape = RoundedCornerShape(8.dp),
                            color = Color(0xFF1B2332),
                            border = androidx.compose.foundation.BorderStroke(1.dp, Color(0xFF2C394F)),
                            modifier = Modifier
                                .width(200.dp)
                                .height(130.dp)
                        ) {
                            Box(contentAlignment = Alignment.Center) {
                                Icon(
                                    imageVector = Icons.Default.PlayCircleFilled,
                                    contentDescription = "Play",
                                    tint = Color.White.copy(alpha = 0.8f),
                                    modifier = Modifier.size(40.dp)
                                )

                                if (captionsGenerated) {
                                    Box(
                                        modifier = Modifier
                                            .align(Alignment.BottomCenter)
                                            .padding(bottom = 12.dp)
                                            .background(Color.Black.copy(alpha = 0.7f), RoundedCornerShape(4.dp))
                                            .padding(horizontal = 6.dp, vertical = 2.dp)
                                    ) {
                                        Text(
                                            text = "Auto Subtitles Active",
                                            color = Color.Yellow,
                                            fontSize = 9.sp,
                                            fontWeight = FontWeight.Bold
                                        )
                                    }
                                }
                            }
                        }

                        Spacer(modifier = Modifier.height(6.dp))
                        Text(
                            text = "00:04.12 / 00:30.00",
                            style = MaterialTheme.typography.labelSmall,
                            color = TextSecondary,
                            fontFamily = FontFamily.Monospace
                        )
                    }

                    // Click Ripple Marker
                    if (animatedRippleAlpha > 0.05f) {
                        Canvas(modifier = Modifier.fillMaxSize()) {
                            drawCircle(
                                color = NeonCyan.copy(alpha = animatedRippleAlpha),
                                radius = 28f,
                                center = tapRippleOffset ?: Offset(size.width / 2, size.height / 2)
                            )
                        }
                    }
                }
            }

            // Timeline Tracks Area
            Surface(
                color = Color(0xFF0D1219),
                modifier = Modifier
                    .fillMaxWidth()
                    .weight(1.1f)
            ) {
                Box(modifier = Modifier.fillMaxSize()) {
                    // Scrollable Tracks
                    Row(
                        modifier = Modifier
                            .fillMaxSize()
                            .horizontalScroll(timelineScrollState)
                            .padding(vertical = 8.dp)
                    ) {
                        Spacer(modifier = Modifier.width(140.dp))

                        Column(
                            verticalArrangement = Arrangement.spacedBy(6.dp),
                            modifier = Modifier.fillMaxHeight()
                        ) {
                            // Timeline Timecode Ruler
                            Row(
                                horizontalArrangement = Arrangement.spacedBy(40.dp),
                                modifier = Modifier.padding(bottom = 4.dp)
                            ) {
                                listOf("00:00", "00:02", "00:04", "00:06", "00:08", "00:10", "00:12", "00:14").forEach { time ->
                                    Text(text = time, style = MaterialTheme.typography.labelSmall, color = TextTertiary, fontSize = 9.sp)
                                }
                            }

                            // Main Video Track
                            Row(horizontalArrangement = Arrangement.spacedBy(4.dp)) {
                                clips.forEachIndexed { idx, name ->
                                    Surface(
                                        shape = RoundedCornerShape(6.dp),
                                        color = if (name.contains("Ending")) SunsetRose.copy(alpha = 0.4f) else if (idx % 2 == 0) TimelineClipA else TimelineClipB,
                                        border = androidx.compose.foundation.BorderStroke(
                                            1.dp,
                                            if (highlightedButtonText?.equals(name, ignoreCase = true) == true) NeonCyan else Color.White.copy(alpha = 0.2f)
                                        ),
                                        modifier = Modifier
                                            .width(if (name.contains("Ending")) 70.dp else 110.dp)
                                            .height(44.dp)
                                    ) {
                                        Box(contentAlignment = Alignment.Center) {
                                            Text(
                                                text = name.take(12),
                                                style = MaterialTheme.typography.labelSmall,
                                                color = Color.White,
                                                fontSize = 9.sp,
                                                fontWeight = FontWeight.Bold
                                            )
                                        }
                                    }
                                }
                            }

                            // Audio Waveform Track
                            Surface(
                                shape = RoundedCornerShape(4.dp),
                                color = Color(0xFF13271F),
                                border = androidx.compose.foundation.BorderStroke(0.5.dp, EmeraldGlow.copy(alpha = 0.3f)),
                                modifier = Modifier
                                    .width(360.dp)
                                    .height(24.dp)
                            ) {
                                Row(
                                    verticalAlignment = Alignment.CenterVertically,
                                    modifier = Modifier.padding(horizontal = 8.dp)
                                ) {
                                    Icon(imageVector = Icons.Default.GraphicEq, contentDescription = null, tint = EmeraldGlow, modifier = Modifier.size(14.dp))
                                    Spacer(modifier = Modifier.width(6.dp))
                                    Text("BGM Beat Audio Track", color = EmeraldGlow, fontSize = 9.sp)
                                }
                            }

                            // Text / Captions Track
                            if (captionsGenerated) {
                                Surface(
                                    shape = RoundedCornerShape(4.dp),
                                    color = Color(0xFF352B11),
                                    border = androidx.compose.foundation.BorderStroke(0.5.dp, AmberGlow.copy(alpha = 0.4f)),
                                    modifier = Modifier
                                        .width(340.dp)
                                        .height(22.dp)
                                ) {
                                    Row(
                                        verticalAlignment = Alignment.CenterVertically,
                                        modifier = Modifier.padding(horizontal = 8.dp)
                                    ) {
                                        Icon(imageVector = Icons.Default.Subtitles, contentDescription = null, tint = AmberGlow, modifier = Modifier.size(12.dp))
                                        Spacer(modifier = Modifier.width(6.dp))
                                        Text("Auto Captions (Synced)", color = AmberGlow, fontSize = 9.sp)
                                    }
                                }
                            }
                        }

                        Spacer(modifier = Modifier.width(200.dp))
                    }

                    // Red Playhead Needle in Center
                    Box(
                        modifier = Modifier
                            .align(Alignment.Center)
                            .width(2.dp)
                            .fillMaxHeight()
                            .background(TimelinePlayhead)
                    )
                }
            }

            // Mock CapCut Bottom Editing Toolbar
            Surface(
                shape = RoundedCornerShape(bottomStart = 16.dp, bottomEnd = 16.dp),
                color = Color(0xFF141A23),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .horizontalScroll(rememberScrollState())
                        .padding(horizontal = 8.dp, vertical = 10.dp),
                    horizontalArrangement = Arrangement.spacedBy(14.dp)
                ) {
                    val toolbarItems = listOf(
                        "Edit" to Icons.Default.Edit,
                        "Split" to Icons.Default.ContentCut,
                        "Speed" to Icons.Default.Speed,
                        "Text" to Icons.Default.TextFields,
                        "Auto captions" to Icons.Default.Subtitles,
                        "Effects" to Icons.Default.AutoFixHigh,
                        "Ratio" to Icons.Default.AspectRatio,
                        "Delete" to Icons.Default.Delete,
                        "Canvas" to Icons.Default.Wallpaper
                    )

                    toolbarItems.forEach { (label, icon) ->
                        val isHighlighted = highlightedButtonText?.equals(label, ignoreCase = true) == true
                        Column(
                            horizontalAlignment = Alignment.CenterHorizontally,
                            modifier = Modifier
                                .clip(RoundedCornerShape(8.dp))
                                .background(if (isHighlighted) NeonCyan.copy(alpha = 0.3f) else Color.Transparent)
                                .border(
                                    width = if (isHighlighted) 1.5.dp else 0.dp,
                                    color = if (isHighlighted) NeonCyan else Color.Transparent,
                                    shape = RoundedCornerShape(8.dp)
                                )
                                .padding(horizontal = 8.dp, vertical = 4.dp)
                        ) {
                            Icon(
                                imageVector = icon,
                                contentDescription = label,
                                tint = if (isHighlighted) NeonCyan else Color.White,
                                modifier = Modifier.size(20.dp)
                            )
                            Spacer(modifier = Modifier.height(3.dp))
                            Text(
                                text = label,
                                style = MaterialTheme.typography.labelSmall,
                                color = if (isHighlighted) NeonCyan else TextSecondary,
                                fontSize = 9.sp,
                                fontWeight = if (isHighlighted) FontWeight.Bold else FontWeight.Normal
                            )
                        }
                    }
                }
            }
        }
    }
}
